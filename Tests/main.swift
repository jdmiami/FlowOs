assert(FlowMath.number("nan") == nil && FlowMath.number("inf") == nil)
assert(FlowMath.groups([["Type":"A"],["Type":"A"],["Type":"B"]],category:"Type",measure:nil).first?.1 == 2)
assert(FlowTheme.aurora.isValid)
assert(!FlowTheme(name:"Bad",primary:"#NOTHEX",secondary:"#FFFFFF",accent:"#123456").isValid)
assert(Validation.parse("{\"action\":\"theme\",\"theme\":{\"name\":\"Cloud\",\"primary\":\"#CCCCDD\",\"secondary\":\"#DDEEFF\",\"accent\":\"#FFEEDD\"}}",mode:"theme")?.theme?.name == "Cloud")
print("11 V0.5 schema, compatibility, math and theme checks passed")

