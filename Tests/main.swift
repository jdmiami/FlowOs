import Foundation
let valid = Plan(action: "app", title: "Orders", fields: ["Customer", "Quantity"])
assert(Validation.miniApp(valid)?.fields.count == 2)
assert(Validation.miniApp(Plan(action: "app", title: "", fields: ["X"])) == nil)
assert(Validation.miniApp(Plan(action: "app", title: "Bad", fields: ["X", "X"])) == nil)
assert(Validation.miniApp(Plan(action: "delete", title: "Bad", fields: ["X"])) == nil)
assert(Validation.workflow(Plan(action: "workflow", title: "Morning", steps: ["Read calendar"])) != nil)
assert(Validation.workflow(Plan(action: "workflow", title: "Morning", steps: [])) == nil)
let encoded = try JSONEncoder().encode(Validation.miniApp(valid)!)
let decoded = try JSONDecoder().decode(MiniApp.self, from: encoded)
assert(decoded.title == "Orders")
print("7 validation and serialization checks passed")

assert(Validation.parse("prefix {\"action\":\"app\",\"title\":\"Orders\",\"fields\":[\"Customer\",\"Quantity\"]} suffix", mode: "app") != nil)
assert(Validation.parse("{\"action\":\"app\",\"title\":\"Braces {x}\",\"fields\":[\"Name\"]}", mode: "app") != nil)
assert(Validation.parse("{\"action\":\"app\",\"title\":\"A\",\"fields\":[\"Name\"]", mode: "app") == nil)
assert(Validation.parse("{\"action\":\"workflow\",\"title\":\"A\",\"steps\":[\"Read\"]}", mode: "app") == nil)
let artifact = Artifact(title: "Orders", request: "Track orders", kind: "app", source: "{}", state: "Ready", plan: valid)
let artifactData = try JSONEncoder().encode(artifact)
let restored = try JSONDecoder().decode(Artifact.self, from: artifactData)
assert(restored.plan?.title == "Orders")
print("5 artifact and parser checks passed")

let rich = Plan(action:"app",title:"Inventory",fields:["Product","Quantity","Cost"],components:[FlowComponent(kind:"calculator",field:"Quantity",field2:"Cost"),FlowComponent(kind:"bar",field:"Product",field2:"Quantity")])
assert(Validation.miniApp(rich)?.components?.count == 2)
assert(Validation.miniApp(Plan(action:"app",title:"Invalid",fields:["Name"],components:[FlowComponent(kind:"sum",field:"Missing")])) == nil)
assert(Validation.miniApp(Plan(action:"app",title:"Invalid",fields:["Name"],components:[FlowComponent(kind:"eval",field:"Name")])) == nil)
let legacy = try JSONDecoder().decode(MiniApp.self,from:Data("{\"id\":\"00000000-0000-0000-0000-000000000001\",\"title\":\"Old\",\"fields\":[\"Name\"],\"rows\":[]}".utf8))
assert(legacy.components == nil && legacy.fields == ["Name"])
let values = [["Quantity":"2","Cost":"3"],["Quantity":"4","Cost":"2"]]
assert(FlowMath.product(values,first:"Quantity",second:"Cost") == 14)
assert(FlowMath.sum(values,field:"Quantity") == 6)
assert(FlowMath.number("nan") == nil && FlowMath.number("inf") == nil)
assert(FlowMath.groups([["Type":"A"],["Type":"A"],["Type":"B"]],category:"Type",measure:nil).first?.1 == 2)
assert(FlowTheme.aurora.isValid)
assert(!FlowTheme(name:"Bad",primary:"#NOTHEX",secondary:"#FFFFFF",accent:"#123456").isValid)
assert(Validation.parse("{\"action\":\"theme\",\"theme\":{\"name\":\"Cloud\",\"primary\":\"#CCCCDD\",\"secondary\":\"#DDEEFF\",\"accent\":\"#FFEEDD\"}}",mode:"theme")?.theme?.name == "Cloud")
print("11 V0.5 schema, compatibility, math and theme checks passed")
